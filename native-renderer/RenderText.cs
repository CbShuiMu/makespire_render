using System;
using System.Collections.Generic;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using Godot;
using MegaCrit.Sts2.addons.mega_text;
using MegaCrit.Sts2.Core.Assets;

internal static class RenderText
{
    private static readonly Regex Tokens = new(@"\[/?[a-z_]+\]|\*[a-z_]+\*", RegexOptions.Compiled);
    private static readonly HashSet<string> Tags = new() {
        "gold", "yellow", "blue", "red", "purple", "green", "aqua", "orange", "pink", "b", "i", "center"
    };
    private static string Escape(string text) => text.Replace("[", "[lb]");

    // Whitelist markup. In particular, never allow user-supplied [img], [font],
    // [url], resource paths or animated effects to reach Godot's BBCode loader.
    public static string Format(string text, int iconSize, Texture2D? customEnergy = null)
    {
        var result = new StringBuilder();
        var stack = new Stack<string>();
        int offset = 0;
        foreach (Match match in Tokens.Matches(text))
        {
            result.Append(Escape(text[offset..match.Index]));
            string token = match.Value;
            if (token[0] == '[' && Tags.Contains(token.Trim('[', ']', '/')))
            {
                string tag = token.Trim('[', ']', '/');
                if (token.StartsWith("[/"))
                {
                    if (stack.TryPeek(out var top) && top == tag) { result.Append(token); stack.Pop(); }
                    else result.Append(Escape(token));
                }
                else { result.Append(token); stack.Push(tag); }
            }
            else if (token[0] == '*' && IconPath(token.Trim('*'), customEnergy) is string path)
                result.Append($"[img width={iconSize} height={iconSize}]{path}[/img]");
            else result.Append(Escape(token));
            offset = match.Index + match.Length;
        }
        result.Append(Escape(text[offset..]));
        while (stack.TryPop(out string? tag)) result.Append("[/" + tag + "]");
        return result.ToString();
    }

    private static string? IconPath(string name, Texture2D? custom)
    {
        if (name == "custom_energy" && custom != null)
        {
            const string path = "res://__request_energy.png";
            custom.TakeOverPath(path);
            PreloadManager.Cache.SetAsset(path, custom);
            return path;
        }
        // These trusted bundled PNGs also cover the editor's watcher/custom tokens.
        if (!new HashSet<string> { "colorless_energy", "defect_energy", "fool_energy", "ironclad_energy",
            "necrobinder_energy", "regent_energy", "silent_energy", "star_energy", "watcher_energy" }.Contains(name)) return null;
        return "res://editor_assets/" + (name == "star_energy" ? "star_icon" : name + "_icon") + ".png";
    }

    public static void Set(MegaRichTextLabel label, string text, int size, Texture2D? custom = null) =>
        label.SetTextAutoSize(Format(text, size, custom));

    public static Label Watermark(JsonElement data, Vector2I size)
    {
        int fontSize = (int)Math.Round(size.X * .02);
        int inset = (int)Math.Round(size.X * .022);
        var label = new Label {
            Text = data.Text("language", "zh") == "en" ? "Generated by makespire.app" : "由makespire.app生成",
            Position = new Vector2(inset, size.Y - inset - fontSize * 2),
            Size = new Vector2(size.X - inset * 2, fontSize * 2),
            HorizontalAlignment = HorizontalAlignment.Right, VerticalAlignment = VerticalAlignment.Bottom
        };
        label.AddThemeFontOverride("font", RenderInput.Load<Font>("res://themes/fonts/zhs/noto_sans_mono_cjksc_regular_shared.tres"));
        label.AddThemeFontSizeOverride("font_size", fontSize);
        label.AddThemeColorOverride("font_color", new Color(0, 0, 0, .88f));
        return label;
    }
}
